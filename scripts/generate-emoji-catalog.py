#!/usr/bin/env python3
"""Generates the emoji catalog the reaction picker reads.

Inputs (downloaded unless given as local files):
  Unicode emoji-test.txt   every fully-qualified emoji, with its group,
                           subgroup, name and the emoji version it came in
  CLDR en annotations      search keywords (annotations + annotationsDerived,
                           from the cldr-json packages)

Output: bitchat/Resources/Emoji/emoji-catalog.tsv, UTF-8, one line each:
  @<group>                 a group, in Unicode's order
  ~<subgroup>              a subgroup of the group above
  <emoji>\\t<name>\\t<keywords>\\t<version>\\t<skin tones>
      keywords   CLDR keywords not already in the name, space-separated
      version    the emoji version that added it (e.g. 15.1)
      skin tones the five one-tone variants, space-separated, light to
                 dark; empty when the emoji has none
A skin-tone variant has no line of its own: it rides on its base emoji.
Mixed-tone sequences (two people, two tones) are left out. The Component
group (bare skin tones and hair) holds no fully-qualified emoji and is
skipped.

Usage: python3 scripts/generate-emoji-catalog.py
           [--emoji-version 18.0.0] [--cldr-version 49.0.0]
           [--emoji-test FILE] [--annotations FILE] [--derived FILE]
"""

import argparse
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "bitchat", "Resources", "Emoji", "emoji-catalog.tsv")

TONES = [
    "light skin tone",
    "medium-light skin tone",
    "medium skin tone",
    "medium-dark skin tone",
    "dark skin tone",
]
TONE_MODIFIERS = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}

LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.+)$")


def fetch(url):
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def read(path_or_url):
    if os.path.exists(path_or_url):
        with open(path_or_url, encoding="utf-8") as handle:
            return handle.read()
    return fetch(path_or_url)


def strip_fe0f(text):
    return text.replace("️", "")


def parse_emoji_test(text):
    """Returns [(group, subgroup, emoji, name, version)] for fully-qualified lines."""
    entries = []
    group = subgroup = None
    for raw in text.splitlines():
        if raw.startswith("# group:"):
            group = raw.split(":", 1)[1].strip()
        elif raw.startswith("# subgroup:"):
            subgroup = raw.split(":", 1)[1].strip()
        else:
            match = LINE.match(raw)
            if match:
                codes, _, version, name = match.groups()
                emoji = "".join(chr(int(code, 16)) for code in codes.split())
                entries.append((group, subgroup, emoji, name, version))
    return entries


def load_keywords(annotations_text, derived_text):
    keywords = {}
    for text, root_key, inner_key in (
        (annotations_text, "annotations", "annotations"),
        (derived_text, "annotationsDerived", "annotations"),
    ):
        table = json.loads(text)[root_key][inner_key]
        for emoji, value in table.items():
            keywords.setdefault(strip_fe0f(emoji), value.get("default", []))
    return keywords


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--emoji-version", default="18.0.0")
    parser.add_argument("--cldr-version", default="49.0.0")
    parser.add_argument("--emoji-test")
    parser.add_argument("--annotations")
    parser.add_argument("--derived")
    args = parser.parse_args()

    emoji_test = read(args.emoji_test or f"https://www.unicode.org/Public/{args.emoji_version}/emoji/emoji-test.txt")
    annotations = read(args.annotations or f"https://cdn.jsdelivr.net/npm/cldr-annotations-full@{args.cldr_version}/annotations/en/annotations.json")
    derived = read(args.derived or f"https://cdn.jsdelivr.net/npm/cldr-annotations-derived-full@{args.cldr_version}/annotationsDerived/en/annotations.json")
    version_match = re.search(r"^# Version: (\S+)", emoji_test, re.M)
    keywords = load_keywords(annotations, derived)

    entries = parse_emoji_test(emoji_test)
    by_name = {name: emoji for _, _, emoji, name, _ in entries}
    tones_of = {}
    for _, _, emoji, name, _ in entries:
        base_name, sep, tone = name.rpartition(": ")
        if sep and tone in TONES and base_name in by_name:
            tones_of.setdefault(by_name[base_name], {})[tone] = emoji

    lines = [
        "# Emoji catalog for the reaction picker. Generated by",
        "# scripts/generate-emoji-catalog.py; do not edit by hand.",
        f"# Unicode emoji {version_match.group(1) if version_match else args.emoji_version}, CLDR {args.cldr_version} (en keywords).",
    ]
    group = subgroup = None
    count = 0
    for entry_group, entry_subgroup, emoji, name, version in entries:
        if any(ord(scalar) in TONE_MODIFIERS for scalar in emoji):
            continue  # rides on its base emoji
        if entry_group != group:
            group = entry_group
            lines.append(f"@{group}")
        if entry_subgroup != subgroup:
            subgroup = entry_subgroup
            lines.append(f"~{subgroup}")
        name_words = set(re.findall(r"[\w']+", name.lower()))
        extra = []
        for keyword in keywords.get(strip_fe0f(emoji), []):
            keyword = keyword.lower().strip()
            if keyword and not set(re.findall(r"[\w']+", keyword)) <= name_words and keyword not in extra:
                extra.append(keyword.replace("\t", " "))
        variants = tones_of.get(emoji, {})
        tones = " ".join(variants[tone] for tone in TONES) if len(variants) == len(TONES) else ""
        lines.append("\t".join([emoji, name, " ".join(extra), version, tones]))
        count += 1

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"wrote {count} emoji to {os.path.relpath(OUTPUT, ROOT)} ({os.path.getsize(OUTPUT)} bytes)")


if __name__ == "__main__":
    sys.exit(main())
